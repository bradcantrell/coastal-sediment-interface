#!/usr/bin/env bash
# Build XBeach natively on Windows with MSYS2. No WSL, no Docker.
#
#   /c/msys64/usr/bin/bash.exe dev/build-xbeach-msys2.sh [destination]
#
# Default destination is /d/workspace/xbeach-src. Produces
# <destination>/src/xbeach/.libs/xbeach.exe, serial, without MPI or netCDF.
set -euo pipefail

DEST="${1:-/d/workspace/xbeach-src}"
SRC_URL="https://github.com/openearth/xbeach.git"

echo "== pacman dependencies =="
pacman -S --noconfirm --needed \
  mingw-w64-x86_64-gcc-fortran mingw-w64-x86_64-make \
  autoconf automake libtool make pkgconf diffutils \
  python python-mako subversion git >/dev/null

export PATH=/mingw64/bin:$PATH
echo "gfortran: $(gfortran --version | head -1)"

echo "== source =="
if [ ! -d "$DEST/.git" ]; then
  GIT_TERMINAL_PROMPT=0 git clone --depth 1 "$SRC_URL" "$DEST"
else
  echo "reusing $DEST"
fi

# gfortran >= 14 rejects bind(c) types holding character(len > 1) components.
# b_arraytype is used only inside mnemoniciso.F90, so relaxing it is safe.
# carraytype MUST keep bind(c): introspection.F90 passes it through a bind(C)
# procedure, and dropping it fails there instead.
python - "$DEST/src/xbeachlibrary/mnemoniciso.F90" <<'PY'
import sys
p = sys.argv[1]
s = open(p, encoding='utf-8', errors='replace').read()
if 'type, bind(c) :: b_arraytype' in s:
    open(p, 'w', encoding='utf-8').write(
        s.replace('type, bind(c) :: b_arraytype', 'type :: b_arraytype', 1))
    print('relaxed bind(c) on b_arraytype')
else:
    print('b_arraytype already relaxed')
PY

cd "$DEST"

echo "== configure =="
./autogen.sh >/dev/null 2>&1
./configure --without-mpi --without-netcdf >/dev/null

# .inc files are BUILT_SOURCES generated by one script that needs mako.
# Cleaning first avoids stale .mod files silently reproducing an old error.
echo "== generated includes =="
make clean >/dev/null 2>&1 || true
(cd src/xbeachlibrary && python ../../scripts/generate.py >/dev/null)
echo "  $(ls src/xbeachlibrary/*.inc | wc -l) include files"

# Serial: parallel make races the .mod files and fails on logging_module.mod.
echo "== build =="
make

echo
echo "built: $DEST/src/xbeach/.libs/xbeach.exe"
